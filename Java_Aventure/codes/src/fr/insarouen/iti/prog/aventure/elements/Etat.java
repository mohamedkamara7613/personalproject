package fr.insarouen.iti.prog.aventure.elements;

/**
 * Enumeration representant l'etat d'un element (porte, coffre, AK-47 etc.).
 */
public enum Etat {
	/** L'element est casse. */
	CASSE,
	/** L'element est ferme. */
	FERME,
	/** L'element est ouvert. */
	OUVERT,
	/** L'element est verrouille. */
	VERROUILLE,
	/** L'element est deverrouille. */
	DEVERROUILLE
};
